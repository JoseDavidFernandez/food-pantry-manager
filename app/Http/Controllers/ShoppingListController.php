/**
 * Shopping list of a purchase period (RN-36), persistent and reconciled with the current needs
 * every time it is opened; older lists (other periods and the weekly lists generated by closing
 * a menu before 2026-10-21) are kept as read-only history.
 */
class ShoppingListController extends Controller
{
    public const QUICK_DAYS = [7, 14, 30];

    public function __construct(
        private readonly ShoppingListLocator $locator,
        private readonly ShoppingListEditor $editor,
    ) {}

    public function period(Request $request, ShoppingListSync $sync, PeriodRequirements $requirements, IngredientCatalog $catalog, ReceptionProgress $progress): Response|RedirectResponse
    {
        $validated = $request->validate([
            'days' => ['nullable', 'integer', 'in:'.implode(',', self::QUICK_DAYS)],
            'start' => ['nullable', 'date_format:Y-m-d', 'required_with:end'],
            'end' => ['nullable', 'date_format:Y-m-d', 'required_with:start', 'after_or_equal:start'],
        ], [], ['start' => 'fecha de inicio', 'end' => 'fecha de fin']);

        $today = PeriodRequirements::today();
        $custom = isset($validated['start']);
        $start = $custom ? CarbonImmutable::parse($validated['start'], Week::timezone()) : $today;
        $end = $custom
            ? CarbonImmutable::parse($validated['end'], Week::timezone())
            : $today->addDays((int) ($validated['days'] ?? 7) - 1);

        if ($start->diffInDays($end) >= PeriodRequirements::MAX_DAYS) {
            $end = $start->addDays(PeriodRequirements::MAX_DAYS - 1);
        }

        // A period that is already over generates nothing: no empty list is kept for it.
        if ($end->lessThan($today)) {
            Inertia::flash('toast', ['type' => 'info', 'message' => 'Ese periodo ya ha pasado: las comidas pasadas no generan compras. Consulta el historial.']);

            return to_route('shopping-list.period');
        }

        $household = $this->user($request)->currentHousehold();
        // Quick periods use their moving list; custom dates keep a list per exact period.
        $list = $custom ? $sync->forPeriod($household, $start, $end) : $sync->forRolling($household, (int) ($validated['days'] ?? 7));
        [$start, $end] = [PeriodRequirements::day($list->period_start ?? $start), PeriodRequirements::day($list->period_end ?? $end)];

        // Stock, committed and available per line (RN-36), shown under what to buy.
        $details = [];

        foreach ($requirements->calculate($household, $start, $end) as $line) {
            $details[$line['key']] = [
                'need' => $line['need']->readable(),
                'have' => $line['have']?->readable(),
                // Shown as «≈ previsto · registrado» when they differ (RN-44).
                'registered' => $line['registered'] !== null && ($line['have'] === null || $line['have']->compareTo($line['registered']) !== 0) ? $line['registered']->readable() : null,
                'committed' => $line['committed']?->readable(),
                // RN-47: the recipes and what must stay at home, shown apart in «Ver cálculo».
                'recipes' => $line['recipes']?->readable(),
                'restock' => $line['restock']?->readable(),
                'restock_mode' => $line['restock_mode'],
                'before' => $line['before']?->readable(),
                'available' => $line['available']?->readable(),
                // Rounded up to whole packs (RN-41): what one holds and what is really missing.
                'pack' => $line['pack'],
                'missing' => $line['pack'] === null ? null : $line['missing']?->readable(),
            ];
        }

        return $this->render($request, $household, $list, $catalog, $progress, $details, $requirements->coverage($household, $start, $end));
    }

    /**
     * Old links to a weekly list open that list (history) or the current period.
     */
    public function week(Request $request, string $week): RedirectResponse
    {
        $list = $this->user($request)->currentHousehold()->shoppingLists()
            ->whereHas('menu', fn ($query) => $query->whereDate('week_start', $week))
            ->first();

        return $list === null ? to_route('shopping-list.period') : to_route('shopping-lists.show', $list->id);
    }

    public function index(Request $request): Response
    {
        $household = $this->user($request)->currentHousehold();

        $lists = $household->shoppingLists()->with('menu')->withCount(['items', 'receptions'])->get()
            ->sortByDesc(fn (ShoppingList $list) => $list->range()[0]->format('Y-m-d').sprintf('%010d', $list->id))
            ->map(fn (ShoppingList $list) => [
                'id' => $list->id,
                'label' => $list->label(),
                'kind' => $list->period_start === null ? 'weekly' : ($list->rolling_days === null ? 'period' : 'rolling'),
                'active' => $list->isActive(),
                'items' => $list->items_count,
                'receptions' => $list->receptions_count,
            ])
            ->values();

        return Inertia::render('shopping/History', ['lists' => $lists]);
    }

    public function show(Request $request, int $list, IngredientCatalog $catalog, ReceptionProgress $progress): Response|RedirectResponse
    {
        $household = $this->user($request)->currentHousehold();
        $shoppingList = $this->locator->list($household, $list);

        // The current list of a period is opened through its period, so it is reconciled first.
        if ($shoppingList->isActive()) {
            return to_route('shopping-list.period', $this->periodQuery($shoppingList));
        }

        return $this->render($request, $household, $shoppingList, $catalog, $progress, []);
    }

    public function store(StoreShoppingItemRequest $request, int $list): RedirectResponse
    {
        $shoppingList = $this->locator->list($this->user($request)->currentHousehold(), $list);

        if (! $this->editable($shoppingList)) {
            return back();
        }

        [$item, $merged] = $this->editor->add($shoppingList, $request->ingredient(), $request->itemName(), $request->quantity());

        Inertia::flash('toast', [
            'type' => 'success',
            'message' => $merged ? "«{$item->name}» ya estaba en la lista: se ha actualizado esa línea." : "«{$item->name}» añadido a la lista.",
        ]);

        return back();
    }

    public function update(UpdateShoppingItemRequest $request, int $list, int $item): RedirectResponse
    {
        if ($this->editable($request->item()->shoppingList)) {
            $this->editor->update($request->item(), $request->quantity());
            Inertia::flash('toast', ['type' => 'success', 'message' => 'Línea actualizada.']);
        }

        return back();
    }

    public function destroy(Request $request, int $list, int $item): RedirectResponse
    {
        $line = $this->item($request, $list, $item);

        if ($this->editable($line->shoppingList)) {
            $this->editor->remove($line);
            Inertia::flash('toast', ['type' => 'success', 'message' => "«{$line->name}» quitado de la lista."]);
        }

        return back();
    }

    public function purchased(Request $request, int $list, int $item): RedirectResponse
    {
        $line = $this->item($request, $list, $item);

        if ($this->editable($line->shoppingList)) {
            $this->editor->togglePurchased($line);
        }

        return back();
    }

    public function reviewed(Request $request, int $list, int $item): RedirectResponse
    {
        $line = $this->item($request, $list, $item);

        if ($this->editable($line->shoppingList)) {
            $this->editor->markReviewed($line);
        }

        return back();
    }

    /**
     * Query of the period page that shows this list (quick days when it starts today).
     *
     * @return array<string, string|int>
     */
    public static function periodQuery(ShoppingList $list): array
    {
        if ($list->rolling_days !== null) {
            return ['days' => $list->rolling_days];
        }

        [$start, $end] = $list->range();

        return ['start' => $start->format('Y-m-d'), 'end' => $end->format('Y-m-d')];
    }

    /**
     * @param  array<string, array{need: string, have: string|null, committed: string, available: string|null}>  $details
     * @param  array{dishes: int, past_this_week: int}|null  $coverage
     */
    private function render(Request $request, Household $household, ShoppingList $list, IngredientCatalog $catalog, ReceptionProgress $progress, array $details, ?array $coverage = null): Response
    {
        // Where each food is already kept, to suggest where a purchase goes (RN-46).
        $locations = $household->inventoryItems()->orderBy('location')->get()->groupBy('ingredient_id');

        $items = collect($progress->forList($list))
            ->map(fn (array $line) => $this->itemPayload($line['item'], $line, $details, $locations))
            ->sortBy([
                fn (array $a, array $b) => [$a['is_purchased'] || $a['is_received'], $a['is_received']] <=> [$b['is_purchased'] || $b['is_received'], $b['is_received']],
                fn (array $a, array $b) => strcoll(mb_strtolower($a['name']), mb_strtolower($b['name'])),
            ])
            ->values();

        $typed = $request->old('item');
        $similar = is_string($typed) && $catalog->resolve($household, $typed) === null ? $catalog->similar($household, $typed) : [];
        [$start, $end] = $list->range();
        $query = $list->period_start === null ? null : self::periodQuery($list);

        return Inertia::render('shopping/List', [
            'list' => [
                'id' => $list->id,
                'label' => $list->label(),
                'active' => $list->isActive(),
                'weekly' => $list->period_start === null,
                'start' => $start->format('Y-m-d'),
                'end' => $end->format('Y-m-d'),
                'days' => $query['days'] ?? null,
                'past' => $end->format('Y-m-d') < PeriodRequirements::today()->format('Y-m-d'),
                'regenerated_at' => $list->regenerated_at?->timezone(Week::timezone())->format('d/m/Y H:i'),
                'dismissed_count' => $list->items()->where('is_dismissed', true)->count(),
            ],
            'quickDays' => self::QUICK_DAYS,
            'coverage' => $coverage,
            // One operation per sheet: resending it never adds the stock twice (RN-46).
            'checkedToken' => (string) Str::uuid(),
            'locations' => StorageLocation::options(),
            'items' => $items,
            'receptions' => $list->receptions()->with(['items' => fn ($query) => $query->orderBy('id')])->latest('confirmed_at')->latest('id')->get()
                ->map(fn (Reception $reception) => [
                    'id' => $reception->id,
                    'confirmed_at' => $reception->confirmed_at->timezone(Week::timezone())->format('d/m/Y H:i'),
                    'items' => $reception->items->map(fn (ReceptionItem $line) => [
                        'id' => $line->id,
                        'name' => $line->name,
                        'received' => $line->isReceived(),
                        'unforeseen' => $line->is_unforeseen,
                        'display' => $line->received()?->format(),
                        'location' => $line->location?->label(),
                    ])->values(),
                ]),
            'historyCount' => $household->shoppingLists()->whereKeyNot($list->id)->count(),
            'units' => Unit::options(),
            'suggestions' => $catalog->suggestions($household),
            'similar' => $similar,
            'typed' => $similar === [] ? null : $typed,
        ]);
    }

    /**
     * @param  array{received: list<Quantity>, received_all: list<Quantity>, remaining: Quantity|null, pending: bool, other_units: bool}  $progress
     * @param  array<string, array{need: string, have: string|null, committed: string, available: string|null}>  $details
     * @param  Collection<array-key, EloquentCollection<int, InventoryItem>>  $locations
     * @return array<string, mixed>
     */
    private function itemPayload(ShoppingListItem $item, array $progress, array $details, Collection $locations): array
    {
        $quantity = $item->toQuantity();
        $calculated = $item->calculated();
        // «Guardar lo marcado» suggests what is still missing and where the food is usually kept.
        $suggested = $progress['received_all'] === [] ? $quantity : $progress['remaining'];
        $kept = $locations->get((int) $item->ingredient_id)?->first(fn (InventoryItem $row) => $suggested !== null && $row->unit_group === $suggested->unit->group());

        return [
            'id' => $item->id,
            'name' => $item->name,
            'is_generated' => $item->isGenerated(),
            'has_ingredient' => $item->ingredient_id !== null,
            'quantity' => $quantity?->formattedAmount(),
            'unit' => $item->unit?->value,
            'unit_label' => $quantity !== null ? $item->unit?->label($quantity->amount) : null,
            'unit_group' => $item->unit_group?->value,
            // Calculated lines are totals and use the readable unit; a quantity written by the
            // user (manual or edited line) is shown as it was written.
            'display' => $item->isGenerated() && ! $item->is_user_modified ? $quantity?->readable() : $quantity?->format(),
            'calculated' => $calculated?->readable(),
            'is_user_modified' => $item->is_user_modified,
            'is_purchased' => $item->is_purchased,
            'needs_review' => $item->needs_review,
            'review_reason' => $item->review_reason,
            // Receptions so far (RN-29): everything that arrived for this line and what is still
            // pending. Pending only subtracts what the current quantity does not already account
            // for, so nothing is counted twice.
            'received' => $progress['received_all'] === [] ? null : implode(' + ', array_map(fn (Quantity $q) => $q->readable(), $progress['received_all'])),
            'remaining' => $progress['received_all'] === [] ? null : $progress['remaining']?->readable(),
            'is_received' => ! $progress['pending'],
            'other_units' => $progress['other_units'],
            'detail' => $item->match_key === null ? null : ($details[$item->match_key] ?? null),
            'suggested' => $item->ingredient_id === null || $suggested === null ? null : [
                'quantity' => $suggested->formattedAmount(),
                'unit' => $suggested->unit->value,
                'location' => ($kept !== null ? $kept->location : StorageLocation::defaultFor($item->ingredient?->category))->value,
            ],
        ];
    }

    /**
     * History is read only: only the current list of a period is edited.
     */
    private function editable(ShoppingList $list): bool
    {
        if (! $list->isActive()) {
            Inertia::flash('toast', ['type' => 'error', 'message' => 'Esta lista es del historial y no se puede modificar.']);

            return false;
        }

        return true;
    }

    private function item(Request $request, int $list, int $item): ShoppingListItem
    {
        return $this->locator->item($this->user($request)->currentHousehold(), $list, $item);
    }

    private function user(Request $request): User
    {
        /** @var User $user */
        $user = $request->user();

        return $user;
    }
}
